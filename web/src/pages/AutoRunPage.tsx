import React, { useState } from 'react';
import { Link } from 'react-router-dom';
import { Bot, Play, AlertTriangle } from 'lucide-react';
import { useAutoRuns, useConfiguredEndpoints } from '../api/hooks';
import { startAutoRun } from '../api/endpoints';
import { TelemetrySourcesPanel } from '../components/TelemetrySourcesPanel';
import type { AutoRun, AutoRunState } from '../types';

const STATE_COLORS: Record<AutoRunState, string> = {
  PENDING: '#8b949e',
  DISCOVERING: '#58a6ff',
  ANALYZING: '#58a6ff',
  TESTING: '#f0883e',
  COMPLETED: '#3fb950',
  FAILED: '#f85149',
  CANCELLED: '#8b949e',
};

const ACTIVE: AutoRunState[] = ['PENDING', 'DISCOVERING', 'ANALYZING', 'TESTING'];

const panel = { border: '1px solid #30363d', backgroundColor: '#161b22' };
const th = 'px-3 py-2 text-left font-semibold uppercase tracking-wider';

const errorMessage = (err: unknown): string => {
  const data = (err as { response?: { data?: { error?: string } } })?.response?.data;
  return data?.error ?? (err instanceof Error ? err.message : 'Failed to start auto-run');
};

const StateBadge: React.FC<{ state: string }> = ({ state }) => (
  <span
    className="rounded px-2 py-0.5 font-mono text-[10px] font-semibold"
    style={{ color: STATE_COLORS[state as AutoRunState] ?? '#8b949e', border: '1px solid #30363d' }}
  >
    {state}
  </span>
);

const RunDetail: React.FC<{ run: AutoRun }> = ({ run }) => {
  const report = run.report;
  return (
    <div className="space-y-4">
      <div className="rounded p-4" style={panel}>
        <div className="flex flex-wrap items-center gap-2">
          <StateBadge state={run.state} />
          <span className="font-mono text-[11px]" style={{ color: '#6e7681' }}>{run.id}</span>
        </div>
        {run.phase && <p className="mt-2 text-xs" style={{ color: '#e6edf3' }}>{run.phase}</p>}
        {run.error && (
          <p role="alert" className="mt-2 flex items-start gap-1.5 text-xs" style={{ color: '#f85149' }}>
            <AlertTriangle className="mt-0.5 h-3.5 w-3.5 shrink-0" /> {run.error}
          </p>
        )}
        {run.skipped && run.skipped.length > 0 && (
          <ul className="mt-2 space-y-0.5 text-[11px]" style={{ color: '#d29922' }}>
            {run.skipped.map((s) => <li key={s}>Skipped {s}</li>)}
          </ul>
        )}
      </div>

      {report && (
        <div className="rounded" style={panel}>
          <div className="p-4" style={{ borderBottom: '1px solid #30363d' }}>
            <div className="text-[10px] font-semibold uppercase tracking-widest" style={{ color: '#6e7681' }}>
              Bottleneck
            </div>
            <div className="mt-1 font-mono text-xl font-bold" style={{ color: '#f0883e' }}>
              {report.bottleneck || '—'}
            </div>
            <div className="mt-0.5 text-[11px]" style={{ color: '#6e7681' }}>
              From {report.baseline_traces} baseline and {report.load_traces} loaded traces generated by Damascus
            </div>
          </div>
          <div className="overflow-x-auto">
            <table className="w-full text-xs">
              <thead style={{ color: '#6e7681' }}>
                <tr>
                  <th className={th}>Service</th>
                  <th className={th}>Score</th>
                  <th className={th}>Critical share</th>
                  <th className={th}>P95 critical ms (base → load)</th>
                  <th className={th}>Errors</th>
                  <th className={th}>Reached by</th>
                </tr>
              </thead>
              <tbody>
                {report.services.map((s) => (
                  <tr key={s.service} style={{ borderTop: '1px solid #21262d', color: '#e6edf3' }} title={s.reasons.join('\n')}>
                    <td className="px-3 py-2 font-mono">{s.service}</td>
                    <td className="px-3 py-2 font-mono">{s.score.toFixed(3)}</td>
                    <td className="px-3 py-2 font-mono">{(s.critical_share * 100).toFixed(0)}%</td>
                    <td className="px-3 py-2 font-mono">
                      {s.baseline_critical_ms.toFixed(1)} → {s.load_critical_ms.toFixed(1)}
                      {s.inflation > 1.5 && <span style={{ color: '#f85149' }}> ({s.inflation.toFixed(1)}×)</span>}
                    </td>
                    <td className="px-3 py-2 font-mono">{(s.error_rate * 100).toFixed(1)}%</td>
                    <td className="px-3 py-2" style={{ color: '#8b949e' }}>{s.requests.join(', ')}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}

      {run.experiments.length > 0 && (
        <div className="rounded overflow-x-auto" style={panel}>
          <table className="w-full text-xs">
            <thead style={{ color: '#6e7681' }}>
              <tr>
                <th className={th}>Request</th>
                <th className={th}>Watched service</th>
                <th className={th}>State</th>
                <th className={th}>Outcome</th>
              </tr>
            </thead>
            <tbody>
              {run.experiments.map((e) => (
                <tr key={e.request} style={{ borderTop: '1px solid #21262d', color: '#e6edf3' }}>
                  <td className="px-3 py-2">
                    <span className="font-mono">{e.method}</span> {e.request}
                    <div className="font-mono text-[10px] truncate" style={{ color: '#6e7681' }}>{e.url}</div>
                  </td>
                  <td className="px-3 py-2 font-mono">{e.target_service}</td>
                  <td className="px-3 py-2">{e.state ? <StateBadge state={e.state} /> : '—'}</td>
                  <td className="px-3 py-2" style={{ color: '#8b949e' }}>
                    {e.error ?? e.stop_reason ?? ''}
                    {e.experiment_id && (
                      <Link to={`/experiments/${e.experiment_id}`} className="ml-2" style={{ color: '#58a6ff' }}>
                        details
                      </Link>
                    )}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
};

export const AutoRunPage: React.FC = () => {
  const { data, error, mutate } = useAutoRuns();
  const { data: endpoints } = useConfiguredEndpoints();
  const [selected, setSelected] = useState<string | null>(null);
  const [starting, setStarting] = useState(false);
  const [startError, setStartError] = useState<string | null>(null);
  const [telemetryDirty, setTelemetryDirty] = useState(false);

  const runs = data?.runs ?? [];
  const active = runs.some((r) => ACTIVE.includes(r.state));
  const current = runs.find((r) => r.id === selected) ?? runs[0];
  const requests = endpoints?.requests ?? [];

  const onStart = async () => {
    setStarting(true);
    setStartError(null);
    try {
      const run = await startAutoRun();
      setSelected(run.id);
      await mutate();
    } catch (err) {
      setStartError(errorMessage(err));
    } finally {
      setStarting(false);
    }
  };

  return (
    <div className="space-y-5">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <h1 className="text-base font-semibold" style={{ color: '#e6edf3' }}>Auto Run</h1>
          <p className="text-xs" style={{ color: '#8b949e' }}>
            Replays the requests from <span className="font-mono">.env</span>, traces them through Jaeger, finds the
            bottleneck, and runs capacity experiments against it
          </p>
        </div>
        <button
          type="button"
          onClick={onStart}
          disabled={starting || active || telemetryDirty || requests.length === 0}
          title={telemetryDirty ? 'Test & connect the telemetry sources first' : undefined}
          className="inline-flex items-center gap-1.5 rounded px-3 py-1.5 text-xs font-semibold disabled:opacity-50"
          style={{ backgroundColor: '#238636', color: '#ffffff' }}
        >
          <Play className="h-3 w-3 fill-current" />
          {active ? 'Run in progress' : 'Start auto-run'}
        </button>
      </div>

      {startError && <div role="alert" className="text-xs" style={{ color: '#f85149' }}>{startError}</div>}
      {error && !data && (
        <div className="text-xs" style={{ color: '#f85149' }}>Auto-run status is unavailable: {errorMessage(error)}</div>
      )}

      <TelemetrySourcesPanel onDirtyChange={setTelemetryDirty} />

      <div className="rounded overflow-x-auto" style={panel}>
        <div className="px-3 pt-3 text-[10px] font-semibold uppercase tracking-widest" style={{ color: '#6e7681' }}>
          Configured requests ({requests.length})
        </div>
        {requests.length === 0 ? (
          <p className="p-3 text-xs" style={{ color: '#6e7681' }}>
            No requests configured. Set <span className="font-mono">DAMASCUS_ENDPOINTS</span> in <span className="font-mono">.env</span>.
          </p>
        ) : (
          <table className="w-full text-xs">
            <tbody>
              {requests.map((r) => (
                <tr key={r.name} style={{ borderTop: '1px solid #21262d', color: '#e6edf3' }}>
                  <td className="px-3 py-1.5 font-mono">{r.method}</td>
                  <td className="px-3 py-1.5">{r.name}</td>
                  <td className="px-3 py-1.5 font-mono truncate" style={{ color: '#8b949e' }}>{r.url}</td>
                  <td className="px-3 py-1.5 text-[11px]" style={{ color: r.method !== 'GET' && !r.allow_mutation ? '#d29922' : '#6e7681' }}>
                    {r.method !== 'GET' ? (r.allow_mutation ? 'mutating · allowed' : 'mutating · skipped') : `weight ${r.weight || 1}`}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </div>

      {runs.length === 0 ? (
        <div className="flex h-48 flex-col items-center justify-center gap-2 rounded text-center" style={panel}>
          <Bot className="h-8 w-8" style={{ color: '#30363d' }} />
          <p className="text-xs" style={{ color: '#8b949e' }}>No auto-runs yet</p>
        </div>
      ) : (
        <div className="grid grid-cols-1 gap-5 lg:grid-cols-4">
          <div className="space-y-1 lg:col-span-1">
            {runs.map((r) => (
              <button
                key={r.id}
                type="button"
                onClick={() => setSelected(r.id)}
                className="w-full rounded px-3 py-2 text-left text-xs"
                style={{ ...panel, borderColor: current?.id === r.id ? 'rgba(240,136,62,0.5)' : '#30363d' }}
              >
                <StateBadge state={r.state} />
                <div className="mt-1 font-mono text-[10px]" style={{ color: '#6e7681' }}>
                  {new Date(r.started_at).toLocaleString()}
                </div>
                {r.report?.bottleneck && (
                  <div className="mt-0.5 text-[11px]" style={{ color: '#f0883e' }}>{r.report.bottleneck}</div>
                )}
              </button>
            ))}
          </div>
          <div className="lg:col-span-3">{current && <RunDetail run={current} />}</div>
        </div>
      )}
    </div>
  );
};
